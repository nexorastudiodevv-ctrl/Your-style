function openCart() {
  lastFocusedElement = document.activeElement;
  cartPanel.classList.add("is-open");
  cartPanel.setAttribute("aria-hidden", "false");
  cartPanel.inert = false;
  cartBackdrop.hidden = false;
  document.querySelector("#cart-open").setAttribute("aria-expanded", "true");
  requestAnimationFrame(() => cartBackdrop.classList.add("is-visible"));
  document.querySelector("#cart-close").focus();
}

function closeCart() {
  cartPanel.classList.remove("is-open");
  cartPanel.setAttribute("aria-hidden", "true");
  cartPanel.inert = true;
  cartBackdrop.classList.remove("is-visible");
  document.querySelector("#cart-open").setAttribute("aria-expanded", "false");
  window.setTimeout(() => {
    if (!cartPanel.classList.contains("is-open")) cartBackdrop.hidden = true;
  }, 240);
  if (lastFocusedElement instanceof HTMLElement) lastFocusedElement.focus();
}

document.addEventListener("click", (event) => {
  const target = event.target;
  if (!(target instanceof Element)) return;

  // تغيير صورة اللون يتم عبر تفويض الأحداث حتى تعمل الأزرار بعد إعادة رسم المنتجات.
  const variantButton = target.closest("[data-product-variant]");
  if (variantButton) {
    const productId = Number(variantButton.getAttribute("data-product-variant"));
    const variantIndex = Number(variantButton.getAttribute("data-variant-index"));
    const product = products.find((candidate) => candidate.id === productId);
    const image = product?.images?.[variantIndex];
    const card = variantButton.closest(".product-card");
    const productImage = card?.querySelector("[data-product-image]");
    if (!product || !image || !productImage) return;

    productImage.src = image.src;
    productImage.alt = `${getProductName(product)} - ${getColorName(image)}`;
    const selectedColor = card?.querySelector("[data-selected-color]");
    if (selectedColor) selectedColor.textContent = getColorName(image);
    card.querySelectorAll("[data-product-variant]").forEach((button) => {
      button.setAttribute("aria-pressed", String(button === variantButton));
    });
    return;
  }

  const previewButton = target.closest("[data-image-preview]");
  if (previewButton) {
    const productId = Number(previewButton.getAttribute("data-image-preview"));
    const product = products.find((candidate) => candidate.id === productId);
    const card = previewButton.closest(".product-card");
    const productImage = card?.querySelector("[data-product-image]");
    if (!product || !productImage || !(imagePreview instanceof HTMLDialogElement)) return;

    activePreviewProduct = product;
    const selectedSource = productImage.getAttribute("src");
    const selectedIndex = getProductImages(product).findIndex(
      (image) => image.src === selectedSource,
    );
    activePreviewIndex = selectedIndex >= 0 ? selectedIndex : 0;
    renderPreviewImage();
    imagePreview.showModal();
    return;
  }

  const addButton = target.closest("[data-add-to-cart]");
  if (addButton) {
    const id = Number(addButton.getAttribute("data-add-to-cart"));
    const card = addButton.closest(".product-card");
    const selectedSwatch = card?.querySelector(".color-swatch[aria-pressed='true']");
    const variant = Number(selectedSwatch?.getAttribute("data-variant-index") || 0);
    const item = cart.find((entry) => entry.id === id && entry.variant === variant);
    if (item) {
      item.quantity += 1;
    } else {
      cart.push({ id, quantity: 1, variant });
    }
    updateCart();
    showToast(translate("addedToCart"));
    return;
  }

  const favoriteButton = target.closest("[data-favorite]");
  if (favoriteButton) {
    const isFavorite = favoriteButton.classList.toggle("is-favorite");
    favoriteButton.setAttribute("aria-pressed", String(isFavorite));
    favoriteButton.textContent = isFavorite ? "♥" : "♡";
    showToast(translate(isFavorite ? "addedToFavorites" : "removedFromFavorites"));
    return;
  }

  const quantityButton = target.closest("[data-quantity]");
  if (quantityButton) {
    const id = Number(quantityButton.getAttribute("data-id"));
    const variant = Number(quantityButton.getAttribute("data-variant") || 0);
    const change = Number(quantityButton.getAttribute("data-quantity"));
    const item = cart.find((entry) => entry.id === id && entry.variant === variant);
    if (!item) return;

    item.quantity += change;
    cart = cart.filter((entry) => entry.quantity > 0);
    updateCart();
    return;
  }

  const removeButton = target.closest("[data-remove]");
  if (removeButton) {
    const id = Number(removeButton.getAttribute("data-remove"));
    const variant = Number(removeButton.getAttribute("data-variant") || 0);
    cart = cart.filter((item) => item.id !== id || item.variant !== variant);
    updateCart();
    showToast(translate("removedFromCart"));
    return;
  }

  const categoryButton = target.closest("[data-category]");
  if (categoryButton) {
    setCategory(categoryButton.dataset.category);
  }
});


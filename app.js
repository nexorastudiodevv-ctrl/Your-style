function applyLanguage() {
  const isArabic = currentLanguage === "ar";
  const locale = isArabic ? "ar-EG" : "en-EG";
  numberFormatter = new Intl.NumberFormat(locale);
  currencyFormatter = new Intl.NumberFormat(locale, {
    style: "currency",
    currency: "EGP",
    maximumFractionDigits: 0,
  });

  document.documentElement.lang = currentLanguage;
  document.documentElement.dir = isArabic ? "rtl" : "ltr";
  document.title = translate("pageTitle");

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    element.textContent = translate(key);
    if (key === "heroTitle") element.classList.add("multiline-title");
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.setAttribute("placeholder", translate(element.dataset.i18nPlaceholder));
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", translate(element.dataset.i18nAriaLabel));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((element) => {
    element.setAttribute("title", translate(element.dataset.i18nTitle));
  });
  document.querySelectorAll("[data-i18n-content]").forEach((element) => {
    element.setAttribute("content", translate(element.dataset.i18nContent));
  });

  const languageButton = document.querySelector("#language-toggle");
  languageButton.textContent = isArabic ? "EN" : "عربي";
  languageButton.setAttribute("aria-label", translate("switchLanguage"));
  languageButton.setAttribute("title", translate("language"));

  renderProducts();
  updateCart();
}

function readCart() {
  try {
    const savedCart = JSON.parse(localStorage.getItem("setaylak-cart") || "[]");
    if (!Array.isArray(savedCart)) return [];

    return savedCart.reduce((validItems, item) => {
      if (!item || !Number.isInteger(item.id) || !Number.isInteger(item.quantity) || item.quantity <= 0) {
        return validItems;
      }

      const product = products.find((candidate) => candidate.id === item.id);
      if (!product) return validItems;

      const variant = Number.isInteger(item.variant) ? item.variant : 0;
      const variantCount = product.images?.length || 1;
      if (variant < 0 || variant >= variantCount) return validItems;

      validItems.push({ id: item.id, quantity: item.quantity, variant });
      return validItems;
    }, []);
  } catch (error) {
    console.error("تعذر قراءة سلة المشتريات المحفوظة:", error);
    return [];
  }
}

let cart = readCart();

function saveCart() {
  try {
    localStorage.setItem("setaylak-cart", JSON.stringify(cart));
  } catch (error) {
    console.error("تعذر حفظ سلة المشتريات:", error);
    showToast(translate("storageError"));
  }
}


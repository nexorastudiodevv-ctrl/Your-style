function getVisibleProducts() {
  const normalizedTerm = searchTerm.trim().toLocaleLowerCase(currentLanguage);
  const visibleProducts = products.filter((product) => {
    const matchesCategory =
      activeCategory === "all" || product.category === activeCategory;
    const arabicCategory = Object.keys(categoryKeys).find(
      (category) => categoryKeys[category] === product.category,
    );
    const matchesSearch =
      !normalizedTerm ||
      `${product.nameAr} ${product.nameEn} ${product.descriptionAr || ""} ${product.descriptionEn || ""} ${product.images?.map((image) => `${image.colorAr} ${image.colorEn}`).join(" ") || ""} ${translate(product.category)} ${arabicCategory || ""}`
        .toLocaleLowerCase(currentLanguage)
        .includes(normalizedTerm);
    return matchesCategory && matchesSearch;
  });

  if (sortSelect.value === "price-low") {
    visibleProducts.sort((first, second) => first.price - second.price);
  } else if (sortSelect.value === "price-high") {
    visibleProducts.sort((first, second) => second.price - first.price);
  }

  return visibleProducts;
}

function renderProducts() {
  const visibleProducts = getVisibleProducts();
  productGrid.innerHTML = visibleProducts.map(productCard).join("");
  emptyState.hidden = visibleProducts.length > 0;
  const count = numberFormatter.format(visibleProducts.length);
  const countKey = visibleProducts.length === 1 ? "productsCount" : "productsCountPlural";
  resultsLabel.textContent = translate(countKey, { count });

  document.querySelectorAll(".filter-chip").forEach((button) => {
    const isActive = button.dataset.category === activeCategory;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}

function showToast(message) {
  toast.textContent = message;
  toast.classList.add("is-visible");
  window.clearTimeout(toastTimeout);
  toastTimeout = window.setTimeout(() => {
    toast.classList.remove("is-visible");
  }, 2400);
}

function buildWhatsAppOrderUrl(subtotal, customerDetails) {
  const orderLines = cart.flatMap((item) => {
    const product = products.find((candidate) => candidate.id === item.id);
    if (!product) return [];

    const selectedImage = getProductImages(product)[item.variant];
    const selectedColor =
      selectedImage?.colorAr || selectedImage?.colorEn
        ? ` - ${getColorName(selectedImage)}`
        : "";

    return translate("orderLine", {
      name: `${getProductName(product)}${selectedColor}`,
      quantity: numberFormatter.format(item.quantity),
      unitPrice: formatPrice(product.price),
      lineTotal: formatPrice(product.price * item.quantity),
    });
  });
  const deliveryMessage =
    subtotal > 1500
      ? translate("orderFreeDelivery")
      : translate("orderDeliveryToConfirm");
  const message = [
    translate("orderMessageGreeting"),
    ...orderLines,
    "",
    translate("orderSubtotal", { subtotal: formatPrice(subtotal) }),
    deliveryMessage,
    "",
    translate("orderCustomerDetails", customerDetails),
    translate("orderSizePrompt"),
    translate("orderConfirmPrompt"),
  ].join("\n");

  return `https://wa.me/201152183562?text=${encodeURIComponent(message)}`;
}

function updateCart() {
  const itemCount = cart.reduce((total, item) => total + item.quantity, 0);
  const subtotal = cart.reduce((total, item) => {
    const product = products.find((candidate) => candidate.id === item.id);
    return total + (product ? product.price * item.quantity : 0);
  }, 0);

  const formattedCount = numberFormatter.format(itemCount);
  cartCount.textContent = formattedCount;
  cartCount.setAttribute("aria-label", translate("cartItemCount", { count: formattedCount }));
  cartEmpty.hidden = cart.length > 0;
  cartFooter.hidden = cart.length === 0;
  if (cart.length === 0) {
    checkoutForm.hidden = true;
    checkoutButton.hidden = false;
  }
  cartItemsContainer.innerHTML = cart
    .map((item) => {
      const product = products.find((candidate) => candidate.id === item.id);
      if (!product) return "";
      const productName = getProductName(product);
      const selectedImage = product.images?.[item.variant] || product.images?.[0];
      const selectedColor = selectedImage ? getColorName(selectedImage) : "";
      const cartProductName = selectedColor
        ? `${productName} - ${selectedColor}`
        : productName;

      return `
        <article class="cart-item">
          <img class="cart-item-image" src="${selectedImage?.src || product.image}" alt="" loading="lazy" />
          <div>
            <h3 class="cart-item-title">${cartProductName}</h3>
            <p class="cart-item-price">${formatPrice(product.price)}</p>
            <div class="quantity-controls" aria-label="${translate("quantity")}">
              <button type="button" aria-label="${translate("decreaseQuantity")}" data-quantity="-1" data-id="${product.id}" data-variant="${item.variant}">−</button>
              <span>${numberFormatter.format(item.quantity)}</span>
              <button type="button" aria-label="${translate("increaseQuantity")}" data-quantity="1" data-id="${product.id}" data-variant="${item.variant}">＋</button>
            </div>
          </div>
          <button
            class="remove-item"
            type="button"
            aria-label="${translate("removeProduct", { name: cartProductName })}"
            data-remove="${product.id}"
            data-variant="${item.variant}"
          >×</button>
        </article>
      `;
    })
    .join("");

  cartTotal.textContent = currencyFormatter.format(subtotal);
  saveCart();
}


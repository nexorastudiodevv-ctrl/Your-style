function translate(key, values = {}) {
  const message = translations[currentLanguage][key] || key;
  return message.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? "");
}

function getProductName(product) {
  return currentLanguage === "ar" ? product.nameAr : product.nameEn;
}

function getColorName(image) {
  return currentLanguage === "ar" ? image.colorAr : image.colorEn;
}

function getProductImages(product) {
  return product.images?.length ? product.images : [{ src: product.image }];
}

function renderPreviewImage() {
  if (!activePreviewProduct) return;

  const images = getProductImages(activePreviewProduct);
  const image = images[activePreviewIndex];
  const productName = getProductName(activePreviewProduct);
  const colorName = image.colorAr || image.colorEn ? getColorName(image) : "";
  const caption = colorName ? `${productName} - ${colorName}` : productName;

  document.querySelector("#image-preview-photo").src = image.src;
  document.querySelector("#image-preview-photo").alt = caption;
  document.querySelector("#image-preview-caption").textContent = caption;
  document.querySelector("#image-preview-counter").textContent = translate("imageCounter", {
    current: numberFormatter.format(activePreviewIndex + 1),
    total: numberFormatter.format(images.length),
  });
  document.querySelector("#image-preview-previous").hidden = images.length < 2;
  document.querySelector("#image-preview-next").hidden = images.length < 2;
  document.querySelector("#image-preview-counter").hidden = images.length < 2;
}

function changePreviewImage(direction) {
  if (!activePreviewProduct) return;

  const imageCount = getProductImages(activePreviewProduct).length;
  if (imageCount < 2) return;

  activePreviewIndex = (activePreviewIndex + direction + imageCount) % imageCount;
  renderPreviewImage();
}

